"""Embed Intel's cAVS 1.5 base firmware in the kext as fw_skl.h.

Source: linux-firmware intel/avs/skl/dsp_basefw.bin (also used for Kaby Lake;
Intel redistributable license, see linux-firmware LICENCE.IntcSST2). The
extended manifest ($AE1) is stripped exactly like Linux avs_fw_ext_manifest_strip;
the rest is sent to the DSP ROM as-is.

usage: python3 gen_fw.py [dsp_basefw.bin]   (downloads it when no path is given)
"""
import os, struct, sys, urllib.request

URL = ("https://git.kernel.org/pub/scm/linux/kernel/git/firmware/linux-firmware.git"
       "/plain/intel/avs/skl/dsp_basefw.bin")
EXT_MANIFEST_MAGIC = 0x31454124
SKL_MANIFEST_MAGIC = 0x00000006
SKL_ADSPFW_OFFSET = 0x284
MIN_VERSION = (9, 21, 0, 4732)

data = open(sys.argv[1], "rb").read() if len(sys.argv) > 1 else urllib.request.urlopen(URL).read()
magic, length = struct.unpack_from("<II", data, 0)
if magic == EXT_MANIFEST_MAGIC:
    data = data[length:]
if struct.unpack_from("<I", data, 0)[0] != SKL_MANIFEST_MAGIC:
    sys.exit("not a Skylake-family DSP firmware image")
version = struct.unpack_from("<HHHH", data, SKL_ADSPFW_OFFSET + 28)
if version[:3] != MIN_VERSION[:3] or version[3] < MIN_VERSION[3]:
    sys.exit(f"unexpected firmware version {version}")

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fw_skl.h")
with open(out, "w") as f:
    f.write("// Generated by gen_fw.py from linux-firmware intel/avs/skl/dsp_basefw.bin\n")
    f.write("// ADSPFW %d.%d.%d.%d, extended manifest stripped.\n" % version)
    f.write("static const uint8_t gC434TFirmwareSkl[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("  " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\n")
print(f"wrote {out}: {len(data)} bytes, ADSPFW {'.'.join(map(str, version))}")
