"""Dump an ACPI NHLT table (Intel Non-HD-Audio Link Table): endpoints, formats
and the size/hash of each format's DSP config blob. With --emit, write the blob
of every SSP and PDM (DMIC) format as a C array (used for the C434T audio driver).

usage: python3 nhlt_dump.py nhlt.dat [--emit out.h]
"""
import hashlib, struct, sys

LINK = {0: "HDA", 1: "DSP", 2: "PDM", 3: "SSP"}
DEV = {0: "BT", 1: "DMIC", 4: "I2S"}
DIR = {0: "render", 1: "capture", 2: "render+capture", 3: "render(feedback)"}

data = open(sys.argv[1], "rb").read()
emit = sys.argv[sys.argv.index("--emit") + 1] if "--emit" in sys.argv else None
assert data[:4] == b"NHLT", data[:4]
length = struct.unpack_from("<I", data, 4)[0]
count = data[36]
off = 37
blobs = []
for e in range(count):
    (ep_len, link, instance, vendor, device, rev, subsys_vendor, subsys_device, dev_type,
     direction, bus_id) = struct.unpack_from("<IBBHHHHHBBB", data, off)
    p = off + 19  # endpoint header is 19 bytes (packed)
    cfg_size = struct.unpack_from("<I", data, p)[0]
    p += 4 + cfg_size
    nfmt = data[p]
    p += 1
    print(f"endpoint {e}: link {LINK.get(link, link)} dev {DEV.get(dev_type, dev_type)} "
          f"dir {DIR.get(direction, direction)} virtual bus {bus_id} device {device:#x} "
          f"({nfmt} formats)")
    for f in range(nfmt):
        (tag, ch, rate, bps, align, bits, cb, valid, chmask) = struct.unpack_from(
            "<HHIIHHHHI", data, p)
        p += 40  # WAVEFORMATEXTENSIBLE
        bsize = struct.unpack_from("<I", data, p)[0]
        blob = data[p + 4:p + 4 + bsize]
        p += 4 + bsize
        print(f"  fmt {f}: {rate} Hz {ch} ch {bits}-bit container, {valid} valid, "
              f"chmask {chmask:#x}, blob {bsize} bytes sha1 {hashlib.sha1(blob).hexdigest()[:12]}")
        if LINK.get(link) in ("SSP", "PDM"):
            blobs.append((LINK[link], bus_id, direction, rate, ch, bits, valid, blob))
    off += ep_len

if emit:
    with open(emit, "w") as fh:
        fh.write("// Generated by tools/nhlt_dump.py from the C434T's ACPI NHLT table.\n")
        for i, (kind, bus, d, rate, ch, bits, valid, blob) in enumerate(blobs):
            words = struct.unpack("<%dI" % (len(blob) // 4), blob)
            name = kind.capitalize()
            fh.write(f"// {kind}{bus} {DIR.get(d, d)} {rate} Hz {ch} ch {bits}-bit ({valid} valid)\n")
            fh.write(f"static const uint32_t gNhlt{name}{bus}Dir{d}Fmt{i}[{len(words)}] = {{\n")
            for j in range(0, len(words), 6):
                fh.write("  " + ", ".join("%#010x" % w for w in words[j:j + 6]) + ",\n")
            fh.write("};\n")
    print("wrote", emit)
